#!/usr/bin/env python3
"""
Convert ASTRA CSV → C source with packed stub_telemetry_frame_t frames.

On STM32 there is no filesystem: this "file" is compiled into flash and played
back by firmware instead of UART (see TELEM_SOURCE_PLAYBACK in main snippet).

Usage:
  python3 scripts/csv_to_telem_playback.py --csv data/converted/astra_3d.csv
  python3 scripts/csv_to_telem_playback.py --csv data/converted/or_3d.csv --stride 5 --limit 800
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Reuse the same frame/state logic as UART replay.
_REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "scripts"))
from replay_telemetry_uart import FRAME_SIZE, _build_rows  # noqa: E402

DEFAULT_OUT_H = _REPO / "firmware" / "astra" / "telem_playback_data.h"
DEFAULT_OUT_C = _REPO / "firmware" / "astra" / "telem_playback_data.c"


def _c_float(x: float) -> str:
    s = f"{x:.9g}"
    if "e" in s or "E" in s:
        return s + ("f" if "f" not in s.lower() else "")
    if "." not in s:
        s += ".0"
    return s + "f"


def write_files(
    frames: list[tuple[int, int, float, float, float, float]],
    out_h: Path,
    out_c: Path,
    source_csv: Path,
) -> None:
    n = len(frames)
    out_h.parent.mkdir(parents=True, exist_ok=True)

    try:
        source_label = str(source_csv.resolve().relative_to(_REPO.resolve()))
    except ValueError:
        source_label = str(source_csv)

    out_h.write_text(
        f"""/**
 * @file telem_playback_data.h
 * @brief Generated telemetry table ({n} frames from {source_label}).
 */
#ifndef TELEM_PLAYBACK_DATA_H
#define TELEM_PLAYBACK_DATA_H

#include <stdint.h>

#include "telemetry.h"

#ifdef __cplusplus
extern "C" {{
#endif

#define TELEM_PLAYBACK_FRAME_COUNT  ({n}u)

extern const stub_telemetry_frame_t telem_playback_frames[TELEM_PLAYBACK_FRAME_COUNT];

#ifdef __cplusplus
}}
#endif

#endif /* TELEM_PLAYBACK_DATA_H */
""",
        encoding="utf-8",
    )

    lines: list[str] = [
        f"/* Generated by scripts/csv_to_telem_playback.py from {source_label} — do not edit. */",
        '#include "telem_playback_data.h"',
        "",
        "const stub_telemetry_frame_t telem_playback_frames[TELEM_PLAYBACK_FRAME_COUNT] = {",
    ]
    for state, t_ms, pos_z, vel_z, gps_speed, gps_course in frames:
        lines.append(
            "    {"
            f".state = {state}u, "
            f".timeMs = {t_ms}u, "
            f".posZ = {_c_float(pos_z)}, "
            f".velZ = {_c_float(vel_z)}, "
            f".gpsSpeed = {_c_float(gps_speed)}, "
            f".gpsCourse = {_c_float(gps_course)}"
            "},"
        )
    lines.append("};")
    lines.append("")
    out_c.write_text("\n".join(lines), encoding="utf-8")

    print(f"Wrote {out_h} ({n} frames)")
    print(f"Wrote {out_c} (~{n * FRAME_SIZE} bytes packed)")


def main() -> None:
    p = argparse.ArgumentParser(description="CSV → telem_playback_data.c/.h for STM offline test")
    p.add_argument("--csv", required=True, help="Path to ASTRA CSV")
    p.add_argument("--out-h", type=Path, default=DEFAULT_OUT_H)
    p.add_argument("--out-c", type=Path, default=DEFAULT_OUT_C)
    p.add_argument("--stride", type=int, default=1, help="Keep every Nth row (default: 1)")
    p.add_argument("--limit", type=int, default=0, help="Max frames after stride (0 = all)")
    p.add_argument(
        "--state",
        type=int,
        default=None,
        help="Force state for all frames; default = infer accelerating/free_flight/free_fall",
    )
    args = p.parse_args()

    csv_path = Path(args.csv)
    frames = _build_rows(csv_path, args.state)
    if args.stride > 1:
        frames = frames[:: args.stride]
    if args.limit > 0:
        frames = frames[: args.limit]
    if not frames:
        raise SystemExit("No frames produced from CSV")

    write_files(frames, args.out_h, args.out_c, csv_path)


if __name__ == "__main__":
    main()
